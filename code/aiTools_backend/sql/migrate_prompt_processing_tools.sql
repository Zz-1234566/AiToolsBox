3. 判断每条事项的状态：已完成 / 进行中 / 受阻，状态必须准确，不得把未完成的事写成完成。
4. 提炼关键成果：优先选取有交付物、有数据支撑的产出。
5. 梳理问题与风险：未完成的事、被阻塞的事、需要他人配合的事，都要如实列出。
6. 推导下周计划：基于当前进展与未完成项，给出合理的下一步动作。

注意事项：
- 严格基于原始记录，禁止虚构未发生的工作、进度或数据。
- 涉及数字、日期、人名时逐字核对，不得推测。
- 措辞需体现汇报意识：简洁、客观、结论先行，但不得夸大或美化。
- 若输入内容不具备周报属性（如歌词、代码、闲聊），在「本周概要」中如实说明「输入内容不构成有效工作记录」，其余章节留空。', 0);
