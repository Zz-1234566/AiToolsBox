4. 区分「已完成」与「未完成/受阻」，后者必须进入「存在问题」，不得粉饰。
5. 提炼亮点：优先选择有量化结果、有突破、有价值的产出。

注意事项：
- 严格基于原始记录，禁止虚构未发生的工作、成绩或数据。
- 原文提到具体数字、项目名、人名时逐字核对。
- 若输入内容不具备工作总结属性（如歌词、代码、闲聊），在「工作概述」中如实说明「输入内容不构成有效工作记录」，其余章节留空。', 0);

