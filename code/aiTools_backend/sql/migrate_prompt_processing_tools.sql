-- ============================================================

-- 3.1 format
INSERT INTO `sys_ai_prompt`
  (`tool_code`, `prompt_type`, `prompt_use`, `prompt_name`, `prompt_content`, `dr`)
VALUES
  ('work-summary', 'system', 'format', '工作总结-默认格式', '请将输入的工作记录整理为一份正式、结构清晰的工作总结，严格按以下格式输出：

# 工作总结

## 工作概述
用 3-5 句话说明本次工作的整体情况、主要方向与取得的整体成果。

## 完成事项
按业务模块或时间顺序分点列出，每条以「1. 2. 3.」编号，写明「做了什么 + 达到什么效果」。

## 工作亮点
列出有价值的成果、突破或超出预期的部分，每条以「- 」开头，并尽量给出量化结果。

## 存在问题
列出未完成事项、遇到的阻碍与需要协调的问题，每条以「- 」开头。
无此类内容时该章节写「无」。

## 下一步计划
列出后续计划与建议动作，每条以「- 」开头，写明「做什么 + 预期目标」。

输出要求：
1. 只输出 Markdown 正文，不得有任何开场白、说明文字或代码块包裹（禁止 ```markdown）。
2. 必须使用上述二级标题，顺序不得调整，不得增删章节。
3. 完成事项最多 10 条，亮点最多 5 条。
4. 全部使用简体中文，不使用「总的来说」「希望领导批准」等套话。', 0);

